// Merge ranks (defined in ranks.ts) into every faction so the FactionRank UI is data-driven.
export const FACTIONS: Faction[] = _FACTIONS_BASE.map((f) => ({
  ...f,
  ranks: FACTION_RANKS[f.id] ?? f.ranks,
}));

export function findFaction(id: string): Faction | undefined {
  return FACTIONS.find((f) => f.id === id);
}
